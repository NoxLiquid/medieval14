using System;
using System.Collections.Generic;
using Content.Shared.Administration;
using Content.Shared._Corvax.TTS;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client.Administration.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class AdminAnnounceWindow : DefaultWindow
    {
        [Dependency] private ILocalizationManager _localization = default!;
        [Dependency] private IPrototypeManager _prototype = default!;

        // Respiral: все голоса TTS (id + локализованное имя), отсортированы по имени
        private readonly List<(string Id, string Name)> _voices = new();

        // Respiral: выбранный голос (id прототипа) либо null — не озвучивать
        public string? SelectedVoice { get; private set; }

        public AdminAnnounceWindow()
        {
            RobustXamlLoader.Load(this);
            IoCManager.InjectDependencies(this);

            Announcement.Placeholder = new Rope.Leaf(_localization.GetString("admin-announce-announcement-placeholder"));
            AnnounceMethod.AddItem(_localization.GetString("admin-announce-type-station"));
            AnnounceMethod.SetItemMetadata(0, AdminAnnounceType.Station);
            AnnounceMethod.AddItem(_localization.GetString("admin-announce-type-server"));
            AnnounceMethod.SetItemMetadata(1, AdminAnnounceType.Server);
            AnnounceMethod.OnItemSelected += AnnounceMethodOnOnItemSelected;
            Announcement.OnKeyBindUp += AnnouncementOnOnTextChanged;

            // Respiral: собрать голоса из прототипов
            foreach (var proto in _prototype.EnumeratePrototypes<TTSVoicePrototype>())
            {
                var name = string.IsNullOrEmpty(proto.Name) ? proto.ID : _localization.GetString(proto.Name);
                _voices.Add((proto.ID, name));
            }
            _voices.Sort((a, b) => string.Compare(a.Name, b.Name, StringComparison.CurrentCultureIgnoreCase));

            VoiceSearch.OnTextChanged += _ => PopulateVoices();
            VoiceList.OnItemSelected += OnVoiceSelected;
            VoiceList.OnItemDeselected += OnVoiceDeselected;
            PopulateVoices();
        }

        // Respiral: заполнить список с учётом строки поиска, сохранив выбор
        private void PopulateVoices()
        {
            var filter = VoiceSearch.Text.Trim();
            VoiceList.Clear();

            // Respiral: "Без голоса" — всегда первым пунктом, без учёта фильтра
            var noneItem = VoiceList.AddItem(_localization.GetString("admin-announce-voice-none"), metadata: null);
            if (SelectedVoice == null)
                noneItem.Selected = true;

            foreach (var (id, name) in _voices)
            {
                if (filter.Length > 0 && !name.Contains(filter, StringComparison.CurrentCultureIgnoreCase))
                    continue;

                var item = VoiceList.AddItem(name, metadata: id);
                if (id == SelectedVoice)
                    item.Selected = true; // визуально, list-событие не триггерит
            }
        }

        private void OnVoiceSelected(ItemList.ItemListSelectedEventArgs args)
        {
            SelectedVoice = VoiceList[args.ItemIndex].Metadata as string;
        }

        private void OnVoiceDeselected(ItemList.ItemListDeselectedEventArgs args)
        {
            SelectedVoice = null;
        }

        private void AnnouncementOnOnTextChanged(GUIBoundKeyEventArgs args)
        {
            AnnounceButton.Disabled = Rope.Collapse(Announcement.TextRope).TrimStart() == "";
        }

        private void AnnounceMethodOnOnItemSelected(OptionButton.ItemSelectedEventArgs args)
        {
            AnnounceMethod.SelectId(args.Id);
            Announcer.Editable = ((AdminAnnounceType?)args.Button.SelectedMetadata ?? AdminAnnounceType.Station) == AdminAnnounceType.Station;
        }
    }
}
