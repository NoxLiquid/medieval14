using Content.Shared._Respiral.Skill;
using System.Numerics;
using Robust.Client.AutoGenerated;
using Robust.Client.GameObjects;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Respiral.Skill;

[GenerateTypedNameReferences]
public sealed partial class SkillsListWindow : DefaultWindow
{
    [Dependency] private IEntityManager _entManager = default!;

    public SkillsListWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
    }

    /// <param name="demonstration">
    ///     true — режим демонстрации чужих навыков: вместо процента показывается тип знания,
    ///     а неоценимые навыки скрываются.
    /// </param>
    public void SetSkills(List<SkillInfo> skills, string? targetName = null, bool demonstration = false)
    {
        SkillsContainer.RemoveAllChildren();

        if (targetName != null)
        {
            TargetNameLabel.Text = targetName;
            TargetNameLabel.Visible = true;
        }
        else
        {
            TargetNameLabel.Visible = false;
        }

        if (skills.Count == 0)
        {
            var noSkillsLabel = new Label
            {
                Text = Loc.GetString("skills-list-no-skills"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 20, 0, 0)
            };
            SkillsContainer.AddChild(noSkillsLabel);
            return;
        }

        var spriteSystem = _entManager.System<SpriteSystem>();

        foreach (var skill in skills)
        {
            var entry = new SkillEntryControl();

            var iconSize = new Vector2(Math.Max(skill.IconSize, 48), Math.Max(skill.IconSize, 48));
            entry.Icon.MinSize = iconSize;
            entry.Icon.SetSize = iconSize;
            entry.Icon.Texture = spriteSystem.Frame0(skill.Icon);

            entry.SetTitle(skill.Name);

            // Неоценимый навык: реального уровня нет — вместо описания показываем сообщение об этом,
            // а прогресс-бар не раскрывает реальный уровень и показывается полным.
            var cantEvaluate = demonstration && !skill.Evaluable;

            var descriptionMessage = new FormattedMessage();
            descriptionMessage.AddText(cantEvaluate
                ? Loc.GetString("skill-knowledge-cant-evaluate")
                : skill.Description);
            entry.DescriptionLabel.SetMessage(descriptionMessage);

            entry.SetProgress(cantEvaluate ? 1f : skill.Progress);

            // Свои навыки — точный процент; демонстрация — тип знания (для неоценимого метка пустая).
            entry.ProgressLabel.Text = !demonstration
                ? $"{(int)(skill.Progress * 100)}%"
                : cantEvaluate
                    ? string.Empty
                    : SkillKnowledge.GetLevelName(skill.Progress);

            SkillsContainer.AddChild(entry);
        }
    }
}
