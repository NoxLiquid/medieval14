using Content.Client.UserInterface.Systems;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Respiral.Skill;

[GenerateTypedNameReferences]
public sealed partial class SkillEntryControl : PanelContainer
{
    [Dependency] private IEntityManager _entManager = default!;

    private const float ProgressBarVerticalMargin = 8f;

    public SkillEntryControl()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
    }

    public void SetTitle(string text)
    {
        var message = new FormattedMessage();
        message.PushTag(new MarkupNode("bold", null, null));
        message.AddText(text);
        message.Pop();

        TitleLabel.SetMessage(message);
    }

    public void SetProgress(float progress)
    {
        ProgressBarControl.Value = progress;

        var color = _entManager.System<ProgressColorSystem>().GetProgressColor(progress);
        var foreground = new StyleBoxFlat { BackgroundColor = color };
        foreground.SetContentMarginOverride(StyleBox.Margin.Vertical, ProgressBarVerticalMargin);
        ProgressBarControl.ForegroundStyleBoxOverride = foreground;
    }
}
